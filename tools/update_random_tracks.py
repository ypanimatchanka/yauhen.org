"""Refresh data/random-tracks.yaml — the pool behind the "random track" mini player.

    docker compose run --rm tools tools/update_random_tracks.py

The QR code / short link https://o0o.app/2o redirects to a random short link
(o0o.app/30, /31, …), each of which points to one YouTube video. A browser can't
read where cross-site redirects lead, so this script follows the link many times,
collects every video it reaches and stores them with their YouTube titles.
Run it again after adding tracks to the o0o.app pool.
"""
import argparse
import json
import re
import time
import urllib.parse
import urllib.request
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "random-tracks.yaml"
UA = {"User-Agent": "Mozilla/5.0 (compatible; yauhen.org-site-builder)"}


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *a, **k):
        return None


opener = urllib.request.build_opener(NoRedirect)


def location(url):
    req = urllib.request.Request(url, headers=UA)
    try:
        opener.open(req, timeout=20)
    except urllib.error.HTTPError as e:
        if e.code in (301, 302, 303, 307, 308):
            return urllib.parse.urljoin(url, e.headers["Location"])
        raise
    return None


def video_id(url):
    p = urllib.parse.urlparse(url)
    if p.netloc.endswith("youtu.be"):
        return p.path.strip("/")
    return urllib.parse.parse_qs(p.query).get("v", [None])[0]


def title_of(vid):
    q = urllib.parse.urlencode({"url": f"https://www.youtube.com/watch?v={vid}", "format": "json"})
    try:
        with urllib.request.urlopen(urllib.request.Request(f"https://www.youtube.com/oembed?{q}", headers=UA), timeout=20) as r:
            return json.load(r).get("title", "")
    except Exception:
        return ""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--link", default="https://o0o.app/2o")
    ap.add_argument("--tries", type=int, default=150, help="how many times to follow the random link")
    ap.add_argument("--reset", action="store_true", help="start a new pool instead of adding to the existing one")
    args = ap.parse_args()

    tracks = {}
    if OUT.exists() and not args.reset:     # keep what earlier runs found: every run only adds tracks
        for t in (yaml.safe_load(OUT.read_text(encoding="utf-8")) or {}).get("tracks", []):
            tracks[t["id"]] = {"id": t["id"], "title": t.get("title", "")}
    before = len(tracks)
    # Both levels are random (o0o.app/2o -> o0o.app/30 -> a video that also varies),
    # so follow the whole chain many times and collect every video reached.
    for _ in range(args.tries):
        url, guard = args.link, 0
        while url and "youtube.com" not in url and "youtu.be" not in url and guard < 8:
            url, guard = location(url), guard + 1
        vid = video_id(url or "")
        if vid and re.fullmatch(r"[\w-]{11}", vid) and vid not in tracks:
            tracks[vid] = {"id": vid, "title": title_of(vid)}
        time.sleep(0.1)
    data = {"link": args.link, "updated": time.strftime("%Y-%m-%d"),
            "tracks": sorted(tracks.values(), key=lambda t: (t.get("title") or "").lower())}
    OUT.write_text("# Generated by tools/update_random_tracks.py — the pool of the random-track mini player.\n"
                   + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=1000), encoding="utf-8")
    print(f"{len(tracks)} tracks in the pool ({len(tracks) - before} new) -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
